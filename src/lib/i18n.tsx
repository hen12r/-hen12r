const dictionaries: Record<UiLanguage, Record<TranslationKey, string>> = { en, fr, rw: en };

export function translate(lang: UiLanguage, key: TranslationKey): string {
  return dictionaries[lang]?.[key] ?? en[key];
}

export function localeFor(lang: UiLanguage): string {
  return lang === 'fr' ? 'fr-FR' : lang === 'rw' ? 'rw-RW' : 'en-GB';
}

interface I18nValue { lang: UiLanguage; t: (key: TranslationKey) => string; locale: string }
const I18nContext = createContext<I18nValue>({ lang: 'en', t: (k) => en[k], locale: 'en-GB' });

export function I18nProvider({ lang, children }: { lang: UiLanguage; children: ReactNode }) {
  const value: I18nValue = { lang, t: (k) => translate(lang, k), locale: localeFor(lang) };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);

/** Maps an error (Supabase, Edge Function or network) to a translated, user-safe message. */
export function errorMessage(t: (k: TranslationKey) => string, err: unknown): string {
  const raw = err instanceof Error ? err.message : typeof err === 'string' ? err : (err as { message?: string })?.message ?? '';
  const code = (err as { code?: string })?.code;
  if (raw.includes('FREE_PLAN_NOTE_LIMIT')) return t('errors.FREE_PLAN_NOTE_LIMIT');
  const key = `errors.${code}` as TranslationKey;
  if (code && key in en) return t(key);
  if (/Failed to fetch|NetworkError|network/i.test(raw)) return t('errors.network');
  return raw && raw.length < 160 ? raw : t('errors.generic');
}
